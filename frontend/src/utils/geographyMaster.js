export const getAvailableStates = (executionsList = [], advanceCircle = null) => {
  if (advanceCircle) {
    return [String(advanceCircle).toUpperCase()];
  }
  const set = new Set(Object.keys(MASTER_GEOGRAPHY));
  executionsList.forEach(ex => {
    const s = (ex.state || ex.circle || '').toUpperCase().trim();
    if (s) set.add(s);
  });
  return Array.from(set).sort();
};

export const getAvailableDistricts = (selectedState = 'ALL', executionsList = []) => {
  const set = new Set();
  const stUpper = (selectedState || 'ALL').toUpperCase().trim();

  Object.entries(MASTER_GEOGRAPHY).forEach(([stKey, distObj]) => {
    if (stUpper === 'ALL' || stKey.toUpperCase() === stUpper || stUpper.includes(stKey.toUpperCase())) {
      Object.keys(distObj).forEach(d => set.add(d));
    }
  });

  executionsList.forEach(ex => {
    const exState = (ex.state || ex.circle || '').toUpperCase().trim();
    const exDist = (ex.district || '').toUpperCase().trim();
    if (!exDist) return;
    if (stUpper === 'ALL' || exState === stUpper || stUpper.includes(exState)) {
      set.add(exDist);
    }
  });

  return Array.from(set).sort();
};

export const getAvailableBlocks = (selectedState = 'ALL', selectedDistrict = 'ALL', executionsList = []) => {
  const set = new Set();
  const stUpper = (selectedState || 'ALL').toUpperCase().trim();
  const distUpper = (selectedDistrict || 'ALL').toUpperCase().trim();

  Object.entries(MASTER_GEOGRAPHY).forEach(([stKey, distObj]) => {
    if (stUpper === 'ALL' || stKey.toUpperCase() === stUpper || stUpper.includes(stKey.toUpperCase())) {
      Object.entries(distObj).forEach(([dKey, blocks]) => {
        if (distUpper === 'ALL' || dKey.toUpperCase() === distUpper || distUpper.includes(dKey.toUpperCase())) {
          blocks.forEach(b => set.add(b));
        }
      });
    }
  });

  executionsList.forEach(ex => {
    const exState = (ex.state || ex.circle || '').toUpperCase().trim();
    const exDist = (ex.district || '').toUpperCase().trim();
    const exBlock = (ex.block || '').toUpperCase().trim();
    if (!exBlock) return;

    const stateMatch = stUpper === 'ALL' || exState === stUpper || stUpper.includes(exState);
    const distMatch = distUpper === 'ALL' || exDist === distUpper || distUpper.includes(exDist);
    if (stateMatch && distMatch) {
      set.add(exBlock);
    }
  });

  return Array.from(set).sort();
};
